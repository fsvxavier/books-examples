// Comando gerador escreve um arquivo Go com a data da geração.
package main

import (
	"flag"
	"fmt"
	"os"
)

func main() {
	saida := flag.String("saida", "gerado.go", "arquivo de saída")
	flag.Parse()
	conteudo := fmt.Sprintf("// Code generated by gerador; DO NOT EDIT.\n\npackage main\n\n// Versao foi gerada automaticamente.\nconst Versao = %q\n", "v1-gerada")
	if err := os.WriteFile(*saida, []byte(conteudo), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "erro:", err)
		os.Exit(1)
	}
}
